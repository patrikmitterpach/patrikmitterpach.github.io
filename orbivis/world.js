const LAND = new Uint8Array(MAP_COLUMNS * MAP_ROWS);

for (let row = 0; row < MAP_ROWS; row += 1) {
        const line = (MAP_LAND_ROWS[row] || "").padEnd(MAP_COLUMNS, " ");

        for (let column = 0; column < MAP_COLUMNS; column += 1) {
                if (line[column] !== " ") LAND[row * MAP_COLUMNS + column] = 1;
        }
}

export function isLand(longitude, latitude) {
        const column = Math.floor(((longitude + 180) / 360) * MAP_COLUMNS);
        const row = Math.floor(((90 - latitude) / 180) * MAP_ROWS);

        if (column < 0 || column >= MAP_COLUMNS || row < 0 || row >= MAP_ROWS) return 0;
        return LAND[row * MAP_COLUMNS + column];
}
